# SECTION 2: CORE FINANCIAL FUNCTIONS
# =============================================================================

def monthly_payment(principal: float, annual_rate: float, years: int) -> float:
    """Calculate monthly mortgage payment (P&I)."""
    if annual_rate == 0:
        return principal / (years * 12)
    r = annual_rate / 12
    n = years * 12
    return principal * (r * (1 + r)**n) / ((1 + r)**n - 1)


def annual_debt_service(principal: float, annual_rate: float, amort_years: int) -> float:
    """Annual debt service (12 * monthly payment)."""
    return monthly_payment(principal, annual_rate, amort_years) * 12


def loan_balance_at_year(principal: float, annual_rate: float, amort_years: int, year: int) -> float:
    """Remaining loan balance at end of given year."""
    r = annual_rate / 12
    n = amort_years * 12
    payments_made = year * 12
    if annual_rate == 0:
        return principal - (principal / n) * payments_made
    balance = principal * ((1 + r)**n - (1 + r)**payments_made) / ((1 + r)**n - 1)
    return max(balance, 0)


def calculate_irr(cash_flows: list, max_iter: int = 1000, tol: float = 1e-6) -> float:
    """Calculate IRR using Newton's method with bounds protection."""
    # Initial guess
    rate = 0.10
    for _ in range(max_iter):
        try:
            npv = sum(cf / (1 + rate)**t for t, cf in enumerate(cash_flows))
            dnpv = sum(-t * cf / (1 + rate)**(t + 1) for t, cf in enumerate(cash_flows))
        except (OverflowError, ZeroDivisionError):
            return 0.0
        if abs(dnpv) < tol:
            break
        new_rate = rate - npv / dnpv
        # Clamp to reasonable range to prevent divergence
        new_rate = max(-0.99, min(new_rate, 10.0))
        if abs(new_rate - rate) < tol:
            return new_rate
        rate = new_rate
    return rate



