    # -----------------------------------------------------------------
    # STEP 6: Sensitivity & Scenario Analysis
    # -----------------------------------------------------------------
    def run_scenarios(self) -> dict:
        """Bull, Base, Bear, and Catastrophe scenario modeling."""
        if "retirement" not in self.results:
            self.solve_retirement_target()

        ret = self.results["retirement"]
        mkt = self.market
        va = self.value_add
        inv = self.investor

        price = ret["purchase_price_per_deal"]
        units = ret["units_needed"]
        noi_year1 = ret["noi_required_per_deal"]
        loan = ret["loan_amount"]
        ads = ret["annual_debt_service"]
        hold = inv.hold_period_years

        scenarios = {}

        scenario_params = {
            "bull": {
                "rent_growth": mkt.annual_rent_growth + 0.01,
                "rent_bump_achieved": 1.0,
                "exit_cap": mkt.exit_cap_rate - 0.010,
                "vacancy": mkt.vacancy_rate - 0.02,
                "refi_rate_delta": -0.005,
                "label": "Full value-add, compressed exit cap, low vacancy",
            },
            "base": {
                "rent_growth": mkt.annual_rent_growth,
                "rent_bump_achieved": 0.80,
                "exit_cap": mkt.exit_cap_rate,
                "vacancy": mkt.vacancy_rate,
                "refi_rate_delta": 0,
                "label": "80% of rent bumps, market exit, normal vacancy",
            },
            "bear": {
                "rent_growth": 0.005,
                "rent_bump_achieved": 0.50,
                "exit_cap": mkt.exit_cap_rate + 0.015,
                "vacancy": mkt.vacancy_rate + 0.03,
                "refi_rate_delta": 0.01,
                "label": "Flat rents, cap expansion, elevated vacancy",
            },
            "catastrophe": {
                "rent_growth": -0.01,
                "rent_bump_achieved": 0.30,
                "exit_cap": mkt.exit_cap_rate + 0.025,
                "vacancy": mkt.vacancy_rate + 0.07,
                "refi_rate_delta": 0.02,
                "label": "Rent decline, rate spike, high vacancy",
            },
        }

        for name, params in scenario_params.items():
            # Project NOI over hold period
            noi_final = noi_year1
            for yr in range(1, hold + 1):
                organic = noi_final * (1 + params["rent_growth"])
                bump = (units * va.rent_bump_per_unit * params["rent_bump_achieved"]
                        * 12 * (1 - mkt.expense_ratio) / hold)  # Phased in
                noi_final = organic + bump

            # Adjust for vacancy change
            vacancy_impact = (params["vacancy"] - mkt.vacancy_rate) * noi_final
            noi_final_adj = noi_final + vacancy_impact  # negative if higher vacancy

            # Exit
            exit_value = noi_final_adj / params["exit_cap"]
            remaining_loan = loan_balance_at_year(
                loan, self.debt.interest_rate, self.debt.amortization_years, hold
            )
            net_proceeds = exit_value * 0.97 - remaining_loan
            total_equity_in = ret["total_cash_to_close"] + units * va.capex_per_unit

            # My personal annual cash flow (average over hold)
            avg_annual_cf = (noi_year1 + noi_final_adj) / 2 - ads
            equity_at_exit = net_proceeds
            equity_multiple = (avg_annual_cf * hold + equity_at_exit) / total_equity_in if total_equity_in > 0 else 0

            # Can I still retire on time?
            meets_retirement = avg_annual_cf * self.retirement.num_properties >= (
                self.retirement.annual_passive_income / (1 - self.retirement.tax_rate)
            )

            # Investor returns in this scenario
            lp_equity = total_equity_in - self.retirement.cash_available
            lp_cf_series = [-lp_equity]
            for yr in range(1, hold + 1):
                yr_noi = noi_year1 + (noi_final_adj - noi_year1) * yr / hold
                yr_cf = yr_noi - ads
                lp_share = yr_cf * (1 - inv.gp_promote_after_pref)
                lp_cf_series.append(lp_share)
            lp_cf_series[-1] += net_proceeds * (1 - inv.gp_promote_after_pref)
            try:
                scenario_irr = calculate_irr(lp_cf_series)
            except:
                scenario_irr = 0

            scenarios[name] = {
                "label": params["label"],
                "noi_at_exit": noi_final_adj,
                "exit_value": exit_value,
                "net_proceeds": net_proceeds,
                "avg_annual_cash_flow": avg_annual_cf,
                "equity_at_exit": equity_at_exit,
                "equity_multiple": equity_multiple,
                "investor_irr": scenario_irr,
                "meets_retirement_goal": meets_retirement,
                "survives": avg_annual_cf > 0 and net_proceeds > 0,
            }

        self.results["scenarios"] = scenarios
        return scenarios


    # -----------------------------------------------------------------
    # STEP 7: GO / NO-GO Decision Framework
    # -----------------------------------------------------------------
    def decision_framework(self) -> dict:
        """Produce final GO / NO-GO / NEGOTIATE recommendation."""
        # Run all analyses if not already done
        if "retirement" not in self.results:
            self.solve_retirement_target()
        if "debt" not in self.results:
            self.validate_debt_structure()
        if "investor" not in self.results:
            self.analyze_investor_marketability()
        if "creative" not in self.results:
            self.analyze_creative_financing()
        if "scenarios" not in self.results:
            self.run_scenarios()

        debt = self.results["debt"]
        inv = self.results["investor"]
        creative = self.results["creative"]
        scenarios = self.results["scenarios"]
        ret = self.results["retirement"]

        # Scoring
        conventional_works = debt["conventional_viable"]
        investor_attractive = inv["can_raise_in_60_days"]
        creative_works = creative["best_structure"] != "NONE"
        bear_survives = scenarios["bear"]["survives"]
        catastrophe_survives = scenarios["catastrophe"]["survives"]
        meets_retirement = scenarios["base"]["meets_retirement_goal"]

        # Decision logic
        if conventional_works and investor_attractive and bear_survives and meets_retirement:
            decision = "GO (CONVENTIONAL)"
            reasoning = (
                f"Deal pencils with conventional debt (DSCR {ret['dscr_actual']:.2f}x), "
                f"investor returns are marketable (Grade {inv['marketability_grade']}), "
                f"survives bear case, and meets retirement cash flow target."
            )
            action = (
                f"Proceed with LOI at ${ret['purchase_price_per_deal']:,.0f}. "
                f"Raise ${inv['total_capital_raise']:,.0f} from {inv['num_investors_needed']} investors."
            )
        elif creative_works and bear_survives and meets_retirement:
            decision = "GO (CREATIVE)"
            reasoning = (
                f"Deal requires creative structure ({creative['best_structure']}) "
                f"but math works. Entry cost: ${creative['min_out_of_pocket']:,.0f}. "
                f"Bear case survives."
            )
            action = (
                f"Approach seller with {creative['best_structure'].lower()} proposal. "
                f"Prepare creative finance pitch deck."
            )
        elif not bear_survives and scenarios["base"]["survives"]:
            decision = "NEGOTIATE"
            reasoning = (
                f"Deal works at base case but too thin for bear scenario. "
                f"Need price reduction or seller concession to create margin of safety."
            )
            # Calculate required price discount for bear case to work
            target_discount = 0.10  # Start with 10%
            action = (
                f"Counter at ${ret['purchase_price_per_deal'] * (1 - target_discount):,.0f} "
                f"({target_discount*100:.0f}% below ask) OR request seller credit/carry."
            )
        else:
            decision = "NO-GO"
            reasoning = (
                f"Spread too thin: cap rate vs debt spread = {debt['spread_cap_vs_debt_bps']:.0f} bps. "
                f"Returns don't justify risk. "
                f"{'Investor returns below threshold. ' if not investor_attractive else ''}"
                f"{'Does not survive bear case. ' if not bear_survives else ''}"
            )
            action = "Pass on this deal. Refine search criteria and move to next opportunity."

        result = {
            "decision": decision,
            "reasoning": reasoning,
            "recommended_action": action,
            "summary_scores": {
                "conventional_financing": "PASS" if conventional_works else "FAIL",
                "investor_marketability": inv["marketability_grade"],
                "creative_viability": "PASS" if creative_works else "FAIL",
                "bear_case_survival": "PASS" if bear_survives else "FAIL",
                "catastrophe_survival": "PASS" if catastrophe_survives else "FAIL",
                "retirement_goal": "PASS" if meets_retirement else "FAIL",
            },
        }
        self.results["decision"] = result
        return result

    # -----------------------------------------------------------------
    # FULL RUN: Execute all analyses
    # -----------------------------------------------------------------
    def run_full_analysis(self) -> dict:
        """Execute complete backward analysis pipeline."""
        self.solve_retirement_target()
        self.validate_debt_structure()
        self.analyze_investor_marketability()
        self.analyze_creative_financing()
        self.generate_deal_criteria()
        self.run_scenarios()
        self.decision_framework()
        return self.results



